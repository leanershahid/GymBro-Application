namespace GymManagmentApplication.Application.Messaging;

// ── Participants (member / trainer) ──────────────────────────────────────────

public class MessagePerson
{
    public ulong UserId { get; set; }
    public string Name { get; set; } = "";
    public string? AvatarUrl { get; set; }
    /// <summary>"trainer" | "member".</summary>
    public string Role { get; set; } = "";
}

public class ConversationSummary
{
    public ulong Id { get; set; }
    public MessagePerson Other { get; set; } = new();
    public string? LastMessage { get; set; }
    public DateTime? LastMessageAt { get; set; }
    /// <summary>The last message was the caller's own.</summary>
    public bool LastMessageMine { get; set; }
    public int Unread { get; set; }
    public bool Muted { get; set; }
}

public class MessageAttachmentDto
{
    /// <summary>"workout" | "plan".</summary>
    public string Type { get; set; } = "";
    /// <summary>The assignment id.</summary>
    public ulong Id { get; set; }
    /// <summary>What the app opens: workout template id / plan id.</summary>
    public ulong TargetId { get; set; }
    public string Title { get; set; } = "";
}

public class DirectMessageDto
{
    public ulong Id { get; set; }
    public string ClientMessageId { get; set; } = "";
    public ulong SenderId { get; set; }
    /// <summary>Sender's name (admin review only; participants know who is who).</summary>
    public string? SenderName { get; set; }
    public bool Mine { get; set; }
    public string Body { get; set; } = "";
    public string? PhotoUrl { get; set; }
    public MessageAttachmentDto? Attachment { get; set; }
    public DateTime CreatedAt { get; set; }
    /// <summary>Participants: the caller reported it. Admin review: anyone reported it.</summary>
    public bool Reported { get; set; }
    public bool Redacted { get; set; }
}

public class ConversationDetail
{
    public ulong Id { get; set; }
    public MessagePerson Other { get; set; } = new();
    /// <summary>"trainer" | "member": the caller's side.</summary>
    public string MySide { get; set; } = "";
    public bool CanSend { get; set; }
    /// <summary>One of <see cref="MessagingBlocks"/> when <see cref="CanSend"/> is false.</summary>
    public string? BlockedReason { get; set; }
    /// <summary>Shown above the composer when the thread is read-only.</summary>
    public string? BlockedNote { get; set; }
    /// <summary>Trainers can link a workout / plan they assigned.</summary>
    public bool CanAttach { get; set; }
    public bool Muted { get; set; }
    /// <summary>The gym's outside-hours notice (members, outside working hours only).</summary>
    public string? HoursNotice { get; set; }
    /// <summary>Footer: "Conversations may be reviewed by the gym for safety."</summary>
    public string ReviewNotice { get; set; } = MessagingRules.ReviewNotice;
    /// <summary>Read receipt: the other side has seen everything up to here.</summary>
    public DateTime? OtherLastReadAt { get; set; }
    /// <summary>Oldest first.</summary>
    public List<DirectMessageDto> Messages { get; set; } = [];
    /// <summary>Older messages exist (ask again with ?before={oldest id}).</summary>
    public bool HasMore { get; set; }
}

public class MessageContact
{
    public MessagePerson Person { get; set; } = new();
    /// <summary>Existing thread with them, if any.</summary>
    public ulong? ConversationId { get; set; }
}

public class OpenConversationBody
{
    /// <summary>The other person's user id (a trainer for members, a client for trainers).</summary>
    public ulong UserId { get; set; }
}

public class SendMessageBody
{
    /// <summary>Generated by the app (e.g. a UUID); resending the same id returns the stored message.</summary>
    public string ClientMessageId { get; set; } = "";
    public string? Body { get; set; }
    public string? PhotoUrl { get; set; }
    /// <summary>Trainers: "workout" | "plan" with the assignment id.</summary>
    public string? AttachmentType { get; set; }
    public ulong? AttachmentId { get; set; }
}

public class MuteBody { public bool Muted { get; set; } }

public class ReportMessageBody { public string? Reason { get; set; } }

public class ReportMessageResult
{
    public ulong MessageId { get; set; }
    /// <summary>The "Staff &amp; trainers" help request raised for it.</summary>
    public ulong? SupportRequestId { get; set; }
}

public class UnreadMessagesResponse { public int Total { get; set; } public int Conversations { get; set; } }

public class MyMessagingSettings
{
    /// <summary>"Allow my trainer to message me".</summary>
    public bool AllowTrainerMessages { get; set; } = true;
}

// ── Admin review ─────────────────────────────────────────────────────────────

public class ReviewConversationSummary
{
    public ulong Id { get; set; }
    public MessagePerson Trainer { get; set; } = new();
    public MessagePerson Member { get; set; } = new();
    public DateTime? LastMessageAt { get; set; }
    public string? LastMessage { get; set; }
    public int MessageCount { get; set; }
    public int ReportedCount { get; set; }
}

public class ReviewConversationDetail
{
    public ulong Id { get; set; }
    public MessagePerson Trainer { get; set; } = new();
    public MessagePerson Member { get; set; } = new();
    public DateTime CreatedAt { get; set; }
    /// <summary>Oldest first, read-only.</summary>
    public List<DirectMessageDto> Messages { get; set; } = [];
    public bool Truncated { get; set; }
}
