namespace GymManagmentApplication.Domain.Entities.Messaging;

// Trainer ↔ member messaging (roadmap feature 8): one conversation per (trainer, member) pair per
// gym, its messages, and each member's "Allow my trainer to message me" switch.
// Mapping: Infrastructure/Data/Configurations/MessagingConfigurations.cs. Every table has a ulong
// TenantId, so AppDbContext's tenant filter applies.

/// <summary>
/// The thread between one trainer and one member of a gym (unique per pair). Read state, mute and
/// the list preview live on the row so the inbox is one query.
/// </summary>
public class Conversation : BaseEntity
{
    public ulong TenantId { get; set; }
    /// <summary>The trainer's login (User id, not the TrainerProfile id).</summary>
    public ulong TrainerUserId { get; set; }
    /// <summary>The member (User id).</summary>
    public ulong MemberUserId { get; set; }

    /// <summary>Null until the first message (the row can exist from "Message" on a client's page).</summary>
    public DateTime? LastMessageAt { get; set; }
    /// <summary>First ~120 characters of the last message (or "Photo"), for the inbox.</summary>
    public string? LastMessagePreview { get; set; }
    public ulong? LastMessageSenderId { get; set; }

    /// <summary>Read receipts: everything up to this instant has been seen by that side.</summary>
    public DateTime? MemberLastReadAt { get; set; }
    public DateTime? TrainerLastReadAt { get; set; }

    /// <summary>That side gets no notifications for this thread.</summary>
    public bool MemberMuted { get; set; }
    public bool TrainerMuted { get; set; }

    /// <summary>Set when the member's account was anonymised: their texts are redacted, the row stays.</summary>
    public DateTime? MemberRedactedAt { get; set; }

    public ICollection<DirectMessage> Messages { get; set; } = [];
}

/// <summary>One message: text (≤ 2000), an optional photo, and (trainers) an optional link to a workout / plan they assigned.</summary>
public class DirectMessage : BaseEntity
{
    public ulong TenantId { get; set; }
    public ulong ConversationId { get; set; }
    public ulong SenderId { get; set; }
    /// <summary>Generated by the app per message; unique per sender, so a retried send is stored once.</summary>
    public string ClientMessageId { get; set; } = "";
    public string Body { get; set; } = "";
    /// <summary>One photo uploaded through /api/uploads (this gym's folder).</summary>
    public string? PhotoUrl { get; set; }

    /// <summary>"workout" (WorkoutAssignment) or "plan" (WorkoutPlanAssignment); null = no attachment.</summary>
    public string? AttachmentType { get; set; }
    /// <summary>The assignment id.</summary>
    public ulong? AttachmentId { get; set; }
    /// <summary>What the app opens: the workout template id / workout plan id.</summary>
    public ulong? AttachmentTargetId { get; set; }
    public string? AttachmentTitle { get; set; }

    /// <summary>A participant reported it to the gym (first report wins; the support request holds the details).</summary>
    public DateTime? ReportedAt { get; set; }
    public ulong? ReportedById { get; set; }
    /// <summary>The "Staff &amp; trainers" support request raised for the report.</summary>
    public ulong? ReportRequestId { get; set; }

    /// <summary>Body/photo removed (member anonymised).</summary>
    public DateTime? RedactedAt { get; set; }

    public Conversation Conversation { get; set; } = default!;
}

/// <summary>A member's messaging preferences (no row = defaults).</summary>
public class MessagingUserSetting : BaseEntity
{
    public ulong TenantId { get; set; }
    public ulong UserId { get; set; }
    /// <summary>"Allow my trainer to message me" (default on). Off = no messaging with trainers either way.</summary>
    public bool AllowTrainerMessages { get; set; } = true;
}

public static class MessageAttachmentTypes
{
    public const string Workout = "workout";
    public const string Plan = "plan";
    public static readonly string[] All = [Workout, Plan];
}
